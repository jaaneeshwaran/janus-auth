def _step_payload(step: ApiStep) -> dict[str, Any]:
    return {
        "step_id": step.step_id,
        "method": step.method,
        "path": step.path_template,
        "principal": step.principal_alias,
        "body": step.json_body,
        "extract": step.extract,
    }


def _summary_flag(report: AdjudicationReport, attribute: str) -> bool:
    summary = report.branch_a_summary
    if summary is None:
        return False
    return bool(getattr(summary, attribute))


def generate_replay_witness(
    plan: CompiledTwinPlan,
    report: AdjudicationReport,
) -> str:
    """Return deterministic, lint-clean Python source for one plan."""
    branch_b_summary = report.branch_b_summary
    expect_b_allow = bool(
        branch_b_summary is not None
        and (branch_b_summary.access_allowed or branch_b_summary.state_mutated)
    )
    branch_a = pprint.pformat(
        [_step_payload(step) for step in plan.branch_a_steps],
        width=88,
        sort_dicts=True,
    )
    branch_b = pprint.pformat(
        [_step_payload(step) for step in plan.branch_b_steps],
        width=88,
        sort_dicts=True,
    )
    return _TEMPLATE.format(
        plan_id=plan.plan_id,
        token_env=pprint.pformat(_TOKEN_ENV, width=88, sort_dicts=True),
        canary=plan.canary,
        probe_type=plan.synthesized.probe_type.value,
        masked_control=plan.masked_control,
        expect_a_leak=_summary_flag(report, "canary_present"),
        expect_a_mutation=_summary_flag(report, "state_mutated"),
        expect_b_allow=expect_b_allow,
        branch_a=branch_a,
        branch_b=branch_b,
    )


def write_replay_witness(
    directory: str | Path,
    plan: CompiledTwinPlan,
    report: AdjudicationReport,
) -> Path:
    """Write ``witness_<plan_id>.py`` and return its path."""
    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    safe_id = _UNSAFE_FILENAME.sub("_", plan.plan_id)
    path = target / f"witness_{safe_id}.py"
    path.write_text(generate_replay_witness(plan, report), encoding="utf-8")
    return path


def witness_is_credential_free(source: str) -> bool:
    """Return True when no known synthetic token appears in the generated source."""
    forbidden = (
        "token_ada",
        "token_bea",
        "token_carl",
        "token_dana",
        "token_admin",
    )
    return not any(token in source for token in forbidden)


